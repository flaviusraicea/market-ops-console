/** Markdown for `docs/accessibility.md`, between the `tab-order` markers. */
export function renderTabOrders(orders: readonly TabOrder[] = TAB_ORDERS): string {
  return orders
    .map(
      (o) =>
        `#### ${o.title}\n\n${o.stops.map((s, i) => `${i + 1}. ${s}`).join("\n")}\n`,
    )
    .join("\n");
}
